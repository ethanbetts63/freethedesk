import { SectionHeader } from '@/components/SectionHeader';
import { money, type WebsitePackage } from '@/lib/servicePricing';

const cellClassName = 'border-b border-border-default px-s py-m text-center sm:px-m';

/**
 * Every package's inclusions in one table. A row is one line a package adds,
 * ticked for that package and every one above it, so the table can never list
 * something the cards above do not.
 */
export function PackageCompare({
  eyebrow,
  packages,
}: {
  eyebrow: string;
  packages: readonly WebsitePackage[];
}) {
  const features = packages.flatMap((item, from) => item.adds.map((line) => ({ line, from })));

  return (
    <section className="bg-surface-tint py-section" id="compare">
      <div className="site-shell">
        <SectionHeader
          eyebrow={eyebrow}
          title="Compare"
          accentTitle="the packages."
          size="display-md"
        />

        {/* The table scrolls inside its own box on a phone; the page never does. */}
        <div className="mt-2xl overflow-x-auto">
          <table className="w-full min-w-[560px] border-collapse bg-surface-page text-body">
            <caption className="sr-only">What each website package includes</caption>
            <thead>
              <tr>
                <th
                  scope="col"
                  className="border-b border-border-default px-m py-m text-left text-label font-heavy tracking-label text-text-subtle uppercase"
                >
                  Included
                </th>
                {packages.map((item) => (
                  <th
                    scope="col"
                    key={item.code}
                    className={`${cellClassName} text-lead font-heavy tracking-[-0.025em] text-text-secondary`}
                  >
                    {item.name}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              <tr>
                <th
                  scope="row"
                  className="border-b border-border-default px-m py-m text-left font-strong"
                >
                  Pages
                </th>
                {packages.map((item) => (
                  <td key={item.code} className={cellClassName}>
                    {item.pages}
                  </td>
                ))}
              </tr>
              <tr>
                <th
                  scope="row"
                  className="border-b border-border-default px-m py-m text-left font-strong"
                >
                  Price per page
                </th>
                {packages.map((item) => (
                  <td key={item.code} className={cellClassName}>
                    {money(item.pagePrice)}
                  </td>
                ))}
              </tr>
              {features.map(({ line, from }) => (
                <tr key={line}>
                  <th
                    scope="row"
                    className="border-b border-border-default px-m py-m text-left font-normal text-text-muted"
                  >
                    {line}
                  </th>
                  {packages.map((item, index) => (
                    <td key={item.code} className={cellClassName}>
                      {index >= from ? (
                        <span className="font-heavy text-action-primary">
                          <span aria-hidden="true">✓</span>
                          <span className="sr-only">Included</span>
                        </span>
                      ) : (
                        <span className="text-text-subtle">
                          <span aria-hidden="true">–</span>
                          <span className="sr-only">Not included</span>
                        </span>
                      )}
                    </td>
                  ))}
                </tr>
              ))}
              <tr>
                <th scope="row" className="px-m py-l text-left text-lead font-heavy">
                  Total
                </th>
                {packages.map((item) => (
                  <td
                    key={item.code}
                    className="px-s py-l text-center text-lead font-heavy tracking-[-0.025em] text-text-primary sm:px-m"
                  >
                    {money(item.total)}
                  </td>
                ))}
              </tr>
            </tbody>
          </table>
        </div>
      </div>
    </section>
  );
}
