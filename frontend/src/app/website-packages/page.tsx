import type { Metadata } from 'next';

import { CaseStudyTeaser } from '@/components/marketing/CaseStudyTeaser';
import { FaqSection } from '@/components/marketing/FaqSection';
import { Hero } from '@/components/marketing/Hero';
import { IndexedFeatureSection } from '@/components/marketing/IndexedFeatureSection';
import { ProjectEnquiry } from '@/components/marketing/ProjectEnquiry';
import { WebsiteJobsBar } from '@/components/marketing/WebsiteJobsBar';
import { WebsitePackageCards } from '@/components/marketing/WebsitePackageCards';
import { FloatingPageCta } from '@/components/FloatingPageCta';
import { ManualAdminCta } from '@/components/ManualAdminCta';
import { PageSchema } from '@/components/PageSchema';
import { SCOOTER_SHOP_GROWTH } from '@/lib/caseStudies';
import { metadataFor } from '@/lib/pages';
import { numberSections } from '@/lib/sectionNumbers';
import { buildOneOffOffer } from '@/lib/seo';
import { getSiteSettingsServer, SERVICE_PRICE_FIELDS } from '@/lib/serverApi';
import { servicePrices } from '@/lib/servicePricing';

import { PackageCompare } from './_components/PackageCompare';
import { notInThePrice, packageFaqs } from './_lib/copy';

const sections = numberSections([
  'Packages',
  'Compare',
  'Not in the price',
  'Proof this works',
  'Common questions',
] as const);

export const metadata: Metadata = metadataFor('/website-packages');

/* Page counts and prices come from the admin, so this page renders per request. */
export const dynamic = 'force-dynamic';

const casePoints = [
  'Indexable stock',
  'Intent-focused pages',
  'Structured data',
  'Measured in Search Console',
];

export default async function WebsitePackagesPage() {
  const prices = servicePrices(await getSiteSettingsServer(SERVICE_PRICE_FIELDS));
  const { packages } = prices;
  const [launch] = packages;
  const offers = packages
    .map((item) => buildOneOffOffer({ price: item.total, name: `${item.name} website package` }))
    .filter(Boolean) as object[];

  return (
    <main className="bg-surface-page text-text-secondary">
      <PageSchema path="/website-packages" serviceOffers={offers.length ? offers : undefined} />
      <Hero
        path="/website-packages"
        eyebrow="Website packages Perth"
        titleLines={['Website packages,']}
        accentTitle="priced per page."
        lead={`Three fixed packages for Perth businesses, from ${prices.websiteFrom} for ${launch.pages} pages. Every page has a price, an extra page costs the same, and you know the total before we start.`}
        primaryHref="#packages"
        primaryLabel="Compare packages"
        secondaryHref="/pricing"
        secondaryLabel="See all our prices"
      />

      <WebsiteJobsBar
        id="packages-hero-end"
        steps={['Pick a package', 'Add pages as you grow', 'Know the total first']}
        ariaLabel="How website packages work"
      />

      <WebsitePackageCards
        eyebrow={sections['Packages']}
        packages={packages}
        lead="Every package is custom designed, built mobile-first and launched with the SEO foundations to be found. Each step up adds pages and the work that makes them earn."
      />

      <PackageCompare eyebrow={sections['Compare']} packages={packages} />

      <IndexedFeatureSection
        id="not-included"
        eyebrow={sections['Not in the price']}
        title="No surprises."
        accentTitle="Here's the rest."
        lead="A package price covers the pages and everything listed with it. These are the only other costs a website has."
        items={notInThePrice(prices)}
      />

      <CaseStudyTeaser
        eyebrow={sections['Proof this works']}
        title={`A Perth website that grew organic clicks ${SCOOTER_SHOP_GROWTH.percent}%.`}
        points={casePoints}
        primaryHref="#enquiry"
        primaryLabel="Tell us your budget"
        showPrimaryAction={false}
      >
        <p>
          Scooter Shop is a Perth scooter dealership. Fast structured pages and focused search
          content grew its organic clicks {SCOOTER_SHOP_GROWTH.percent}% in{' '}
          {SCOOTER_SHOP_GROWTH.span}.
        </p>
      </CaseStudyTeaser>

      <ProjectEnquiry
        id="enquiry"
        eyebrow={null}
        showProjectType={false}
        lead="Not sure a package fits? Give us your budget and what you need, and we'll tell you the most valuable site we can build within it."
      />

      <FloatingPageCta
        label="Tell us your budget"
        href="#enquiry"
        showAfterId="packages-hero-end"
        hideAtId="enquiry"
      />

      <FaqSection
        emitSchema
        eyebrow={sections['Common questions']}
        title="Website package questions."
        items={packageFaqs(prices)}
      />

      <ManualAdminCta
        eyebrow="Start with the useful part"
        title="How many pages does your business need?"
        href="#enquiry"
        buttonLabel="Tell us your budget"
      >
        List your services and the suburbs you work in. That is usually the page count.
      </ManualAdminCta>
    </main>
  );
}
