import type { IndexedFeature } from '@/components/marketing/IndexedFeatureSection';
import { money, type ServicePrices } from '@/lib/servicePricing';
import type { FaqItem } from '@/types/FaqItem';

/** What a package price does not cover, and what it costs instead. */
export function notInThePrice(prices: ServicePrices): readonly IndexedFeature[] {
  return [
    ['Extra pages', "Each extra page costs your package's per-page price, before or after launch."],
    [
      'Changes after launch',
      `New features and changes to finished pages are ${prices.hourlyRate} an hour, agreed before we start.`,
    ],
    [
      'Running costs',
      'Hosting, domain renewals and paid services such as SMS are charged by those providers. We set them out before you commit.',
    ],
  ];
}

export function packageFaqs(prices: ServicePrices): FaqItem[] {
  const list = prices.packages
    .map((item) => `${money(item.total)} for ${item.pages} pages (${item.name})`)
    .join(', ');

  return [
    {
      question: 'How much does a website cost in Perth?',
      answer: `Our packages are ${list}. Each is priced per page, and an extra page costs the package's per-page price.`,
    },
    {
      question: 'What counts as a page?',
      answer:
        'Any page with its own address and its own content: your home page, each service, each suburb you target, your about and contact pages. A guide or article is a page too.',
    },
    {
      question: 'Is a package a template?',
      answer:
        'No. Every package is designed around your business. The package fixes how many pages there are and what is built in, not how the site looks.',
    },
    {
      question: 'What if no package fits?',
      answer:
        'Tell us your budget and what you need, and we will tell you what that buys. Work a package cannot price, such as a web application, starts with a paid discovery.',
      links: [
        { phrase: 'web application', href: '/web-application-development' },
        { phrase: 'paid discovery', href: '/pricing' },
      ],
    },
  ];
}
