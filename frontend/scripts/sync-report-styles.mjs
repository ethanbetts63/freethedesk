#!/usr/bin/env node
/**
 * The report engine's stylesheet, copied into the sample report.
 *
 * The sample report at /seo/sample-report is laid out exactly as a delivered report is (owner, 2026-11-07): the
 * cover across the page, the contents as a menu stuck beside the article, the same cards, tags and type. The
 * engine that renders delivered reports (freetheplatform, `searchconsole/render.py`) inlines its stylesheet into
 * each document; this script copies that stylesheet here, in the engine's own cascade order, so the sample cannot
 * drift from the real thing by hand. It is a renderer boundary (lint-rules.md, "Allowed handwritten CSS"): nothing
 * in the copy is written here, and the copy is never edited.
 *
 * The copy is scoped. The engine's sheet styles a whole document (`html`, `body`, `:root`, bare `h2` and `p`); on
 * the site it styles one box, `.seo-report`, so every rule is nested under that class and the document selectors
 * become the box itself. The `@page` rules are dropped: they would set the paper for whatever page was printed
 * after this one, and the sample is read on a screen. The box is imported in the `components` layer
 * (`_styles/sample.css`), under the utilities, so the drawn screenshots inside it keep their utility classes.
 *
 *   node scripts/sync-report-styles.mjs            rewrite the copy
 *   node scripts/sync-report-styles.mjs --check    fail when the copy is stale
 *
 * When freetheplatform is not beside this repo (Vercel, a lone clone) there is nothing to compare, so the check
 * says so and exits 0; the committed copy is what builds.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const engine = resolve(root, '../../freetheplatform/src/freetheplatform/searchconsole');
const target = join(root, 'src/app/seo/sample-report/_styles/report.generated.css');
const check = process.argv.includes('--check');

if (!existsSync(engine)) {
  console.log('report-styles: freetheplatform is not beside this repo; nothing to compare.');
  process.exit(0);
}

/** The sheets in cascade order, read from render.py's STYLESHEETS tuple so the two never disagree. */
function sheetNames() {
  const render = readFileSync(join(engine, 'render.py'), 'utf8');
  const tuple = render.match(/STYLESHEETS = \(([\s\S]*?)\)/);
  if (!tuple) throw new Error('render.py has no STYLESHEETS tuple.');
  return [...tuple[1].matchAll(/"([a-z]+\.css)"/g)].map((m) => m[1]);
}

/**
 * The engine's rules nested under the box. Comments are kept as they are; in the CSS between them the document
 * selectors become `&` (the box) and the `@page` rules go.
 */
function scoped(css) {
  const parts = css.split(/(\/\*[\s\S]*?\*\/)/);
  const out = parts.map((part, index) => {
    if (index % 2) return part;
    return part
      .replace(/@page[^{]*\{[^}]*\}\s*/g, '')
      .replace(/(^|[\s,{};])(html|body|:root)(?=\s*[,{])/g, '$1&');
  });
  return out.join('');
}

function generate() {
  const names = sheetNames();
  const sheets = names.map((name) => {
    const text = readFileSync(join(engine, 'assets', 'report', name), 'utf8').replace(
      /\r\n/g,
      '\n',
    );
    return `/* ===== ${name} ===== */\n${scoped(text).trim()}\n`;
  });
  return (
    '/* Generated by scripts/sync-report-styles.mjs from freetheplatform/src/freetheplatform/searchconsole/' +
    'assets/report.\n' +
    " * The report engine's stylesheet, nested under .seo-report. Do not edit: change the engine and run\n" +
    ' * `npm run sync:report-styles`. */\n\n' +
    '.seo-report {\n' +
    sheets.join('\n') +
    '}\n'
  );
}

const fresh = generate();
const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';

if (check) {
  if (current !== fresh) {
    console.error(
      '\ncheck-report-styles failed:\n\n• src/app/seo/sample-report/_styles/report.generated.css is not the report ' +
        "engine's current stylesheet. Run `npm run sync:report-styles` and commit the result.\n",
    );
    process.exit(1);
  }
  console.log("report-styles: the sample report carries the engine's current stylesheet.");
} else {
  writeFileSync(target, fresh, 'utf8');
  console.log(`report-styles: wrote ${target.replace(root, '').replace(/\\/g, '/').slice(1)}.`);
}
